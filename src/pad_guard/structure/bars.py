"""Colour bars recognition and alignment tone measurement (SPEC §6.1).

A frame is compared with a reference bars frame generated by FFmpeg (``pal75bars``,
``pal100bars`` or ``smptehdbars``, converted like a BT.709 legal-range master) region by region:
the picture is cut into a grid, the mean Y, Cb and Cr of the centre of each cell are compared
with the reference, and the error is the median absolute difference over the cells (worst of
the three planes). The median keeps the recognition working when a few cells carry a caption
or a logo; the cell margins keep it working when the bar edges are a few pixels off.
"""

from __future__ import annotations

import math
import shutil
import subprocess
from functools import lru_cache
from pathlib import Path

import numpy as np

from pad_guard.decode.audio import AudioGroupDecoder
from pad_guard.decode.video import VideoFrame
from pad_guard.probe.models import AudioTrack
from pad_guard.structure.models import ToneMeasure

PATTERNS = {"ebu_75": "pal75bars", "ebu_100": "pal100bars", "smpte_hd": "smptehdbars"}
GRID_ROWS, GRID_COLS = 12, 16
CELL_MARGIN = 0.2  # share of each cell edge left out of the mean
# A 1 kHz alignment tone is a pure tone: its dominant frequency is within FFT resolution of the
# nominal one. 1 % covers any 1 s window (1 Hz bins) without accepting another tone.
TONE_FREQ_TOLERANCE = 0.01


class BarsError(Exception):
    """Reference bars cannot be generated. The message is user-facing (French)."""


def cell_means(y: np.ndarray, cb: np.ndarray, cr: np.ndarray) -> np.ndarray:
    """(3, GRID_ROWS, GRID_COLS) mean of the centre of each grid cell, per plane."""
    out = np.empty((3, GRID_ROWS, GRID_COLS))
    for p, plane in enumerate((y, cb, cr)):
        h, w = plane.shape
        rows = np.linspace(0, h, GRID_ROWS + 1)
        cols = np.linspace(0, w, GRID_COLS + 1)
        for i in range(GRID_ROWS):
            r0, r1 = rows[i], rows[i + 1]
            m = (r1 - r0) * CELL_MARGIN
            rs = slice(int(math.ceil(r0 + m)), int(math.floor(r1 - m)))
            for j in range(GRID_COLS):
                c0, c1 = cols[j], cols[j + 1]
                n = (c1 - c0) * CELL_MARGIN
                cs = slice(int(math.ceil(c0 + n)), int(math.floor(c1 - n)))
                out[p, i, j] = plane[rs, cs].mean(dtype=np.float64)
    return out


@lru_cache(maxsize=None)
def reference(pattern: str, width: int, height: int) -> np.ndarray:
    """Cell means of the FFmpeg bars ``pattern`` at this size, 4:2:2 10-bit BT.709 legal range."""
    exe = shutil.which("ffmpeg")
    if exe is None:
        raise BarsError("ffmpeg introuvable : installer FFmpeg 6+ et l'ajouter au PATH.")
    proc = subprocess.run(
        [exe, "-v", "error", "-nostdin", "-f", "lavfi", "-i", f"{PATTERNS[pattern]}=s={width}x{height}:r=1:d=1",
         "-frames:v", "1", "-vf", "scale=out_color_matrix=bt709:out_range=tv,format=yuv422p10le",
         "-f", "rawvideo", "-"],
        capture_output=True,
    )
    size = width * height * 2 * 2
    if proc.returncode != 0 or len(proc.stdout) != size:
        raise BarsError(f"mire de référence {pattern} impossible à générer : {proc.stderr.decode(errors='replace')}")
    data = np.frombuffer(proc.stdout, dtype="<u2")
    y = data[: width * height].reshape(height, width)
    chroma = width // 2 * height
    cb = data[width * height: width * height + chroma].reshape(height, width // 2)
    cr = data[width * height + chroma:].reshape(height, width // 2)
    return cell_means(y, cb, cr)


def bars_error(frame: VideoFrame, pattern: str) -> float:
    """Median absolute cell error against ``pattern``, worst plane, in 10-bit code values."""
    frame = frame.as_422_10()
    h, w = frame.y.shape
    diff = np.abs(cell_means(frame.y, frame.cb, frame.cr) - reference(pattern, w, h))
    return round(float(max(np.median(diff[p]) for p in range(3))), 3)


def best_pattern(frame: VideoFrame, patterns: list[str]) -> tuple[str, float]:
    errors = [(bars_error(frame, p), p) for p in patterns]
    error, pattern = min(errors)
    return pattern, error


def measure_tone(path: Path, tracks: list[AudioTrack], start: int, length: int, sample_rate: int) -> list[ToneMeasure]:
    """Dominant frequency and sine-referenced level of each track over ``[start, start + length)``."""
    decoder = AudioGroupDecoder(path, tracks, block_samples=sample_rate // 10)
    parts = []
    for first, block in decoder.blocks():
        end = first + block.shape[1]
        if end <= start:
            continue
        parts.append(block[:, max(start - first, 0): start + length - first])
        if end >= start + length:
            break
    x = np.concatenate(parts, axis=1).astype(np.float64) if parts else np.zeros((len(tracks), 0))
    out = []
    window = np.hanning(x.shape[1]) if x.shape[1] else np.zeros(0)
    for t, samples in zip(tracks, x):
        power = float(np.mean(samples * samples)) if samples.size else 0.0
        if power <= 0:
            out.append(ToneMeasure(track=t.track, frequency_hz=None, level_dbfs=None))
            continue
        spectrum = np.abs(np.fft.rfft(samples * window))
        freq = float(np.argmax(spectrum)) * sample_rate / samples.size
        level = 10 * math.log10(power) + 10 * math.log10(2)  # sine at full scale = 0 dBFS
        out.append(ToneMeasure(track=t.track, frequency_hz=round(freq, 1), level_dbfs=round(level, 2)))
    return out
